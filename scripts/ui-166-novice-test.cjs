// 1.6.9 novice UI: Desu-styled flat home + light rail labels + compact tip (not heavy tour).
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const tl = fs.readFileSync(path.join(root, 'js/ui/task-launcher.js'), 'utf8');
assert.ok(tl.includes("id:'decompose'"), 'decompose task');
assert.ok(tl.includes("id:'story'"), 'story task');
assert.ok(tl.includes('task-rail-label'), 'light rail labels');
assert.ok(!tl.includes('task-section-title'), 'no heavy section titles');
assert.ok(!tl.includes('任务按「常用 / 进阶 / 专业」分组'), 'no heavy grouping copy');
assert.ok(tl.includes('showWhatsNew'), 'whats-new tip');
assert.ok(tl.includes("mnai.whatsNew.1.6.10"), '1.6.10 tip key');
assert.ok(tl.includes('task-whatsnew-tip'), 'compact tip class');
assert.ok(tl.includes('startDecompose') && tl.includes('startStory'), 'wizards');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
assert.ok(html.includes('nai-optin-help'), 'opt-in help');
assert.ok(html.includes('换采样参数') || html.includes('减少角色串脸'), 'simpler labels');
const css = fs.readFileSync(path.join(root, 'css/task-launcher.css'), 'utf8');
assert.ok(css.includes('task-whatsnew-tip'), 'tip css');
assert.ok(css.includes('task-rail-label'), 'rail css');
assert.ok(!css.includes('.task-whatsnew {'), 'no full-screen tour overlay');
console.log('ui-167 novice restyle ok');

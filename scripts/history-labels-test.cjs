'use strict';
const assert = require('assert');
require('../js/core/history-labels.js');
const H = globalThis.HistoryLabels;
const s = objs => ({ objects: objs });
const img = { guid: 'a', type: 'image', left: 0, top: 0, scaleX: 1, scaleY: 1, src: 'h1' };
const txt = { guid: 't', type: 'textbox', text: '早上好 世界', left: 10, top: 10, fill: '#000' };
assert.equal(H.describe(null, s([img])), '开始');
assert.equal(H.describe(s([img]), s([img, txt])), '添加文字「早上好 世界」');
assert.equal(H.describe(s([img, txt]), s([img])), '删除文字「早上好 世界」');
assert.equal(H.describe(s([img]), s([{ ...img, left: 40 }])), '移动图片');
assert.equal(H.describe(s([img]), s([{ ...img, scaleX: 2, scaleY: 2 }])), '缩放图片');
assert.equal(H.describe(s([img]), s([{ ...img, angle: 15 }])), '旋转图片');
assert.equal(H.describe(s([img]), s([{ ...img, visible: false }])), '隐藏图片');
assert.equal(H.describe(s([txt]), s([{ ...txt, text: '晚安' }])), '修改文字「晚安」');
assert.equal(H.describe(s([img]), s([{ ...img, opacity: 0.5 }])), '不透明度 50% · 图片');
assert.equal(H.describe(s([img, txt]), s([txt, img])), '调整图层顺序');
assert.equal(H.describe(s([img]), s([img, { guid: 'f', type: 'image', aiFill: { chosen: 0 } }])), '添加 AI 填充层');
assert.equal(H.describe(s([{ guid: 'f', type: 'image', aiFill: { chosen: 0 } }]), s([{ guid: 'f', type: 'image', aiFill: { chosen: 2 } }])), 'AI 填充：换成第 3 张');
assert.equal(H.describe(s([txt]), s([{ ...txt, fill: '#f00' }])), '改颜色 · 文字「早上好 世界」');
assert.equal(H.describe(s([img, txt]), s([{ ...img, left: 5 }, { ...txt, left: 50 }])), '移动 / 变形 2 个对象');
assert.equal(H.describe(s([]), s([img, txt])), '添加 2 个对象（文字「早上好 世界」…）');
assert.equal(H.describe(s([{ type: 'path' }]), s([{ type: 'path' }, { type: 'path', x: 1 }])), '添加笔画', 'index keys for objects without guid');
console.log('PASS history labels: add/remove/move/scale/rotate/hide/text/opacity/order/AI fill/colour/multi');

"""Small, read-only production audit: no model or binary dependency downloads."""
import json, os, pathlib, socket, subprocess, sys, tempfile, time, urllib.request
from PIL import Image
ROOT=pathlib.Path(sys.argv[1] if len(sys.argv)>1 else os.environ.get('MANGA_AUDIT_ROOT',pathlib.Path(__file__).resolve().parents[2]))
scratch=tempfile.TemporaryDirectory(prefix='manga-startup-audit-')
TMP=pathlib.Path(scratch.name)
try:
 # Same build-system requirement as the verified sam2-1.1.0 sdist. --no-index forbids all downloads.
 fixture=pathlib.Path(tempfile.mkdtemp(prefix='audit-sam2-build-',dir=TMP))
 (fixture/'pyproject.toml').write_text('[build-system]\nrequires = ["torch>=2.5.1"]\nbuild-backend = "setuptools.build_meta"\n')
 e=os.environ.copy();e['SAM2_BUILD_CUDA']='0'
 r=subprocess.run([sys.executable,'-m','pip','install','--dry-run','--no-index','--no-deps',str(fixture)],capture_output=True,text=True,env=e)
 assert r.returncode != 0 and 'Installing build dependencies' in r.stdout
 assert 'torch>=2.5.1' in r.stderr
 print('CONFIRMED: --no-deps and SAM2_BUILD_CUDA=0 still enter isolated torch build dependency installation.')
 print(r.stdout+r.stderr)
 # The actual Python -c text generated by prepare-installer.ps1:101 on a legal apostrophe path.
 p=pathlib.Path(tempfile.mkdtemp(prefix="O'Brien Manga 测试-",dir=TMP))
 s=p/'icon.png';o=p/'app.ico';Image.new('RGBA',(16,16),'red').save(s)
 code=f"from PIL import Image; im=Image.open(r'{s}').convert('RGBA'); im.save(r'{o}', sizes=[(16,16)])"
 r=subprocess.run([sys.executable,'-c',code],capture_output=True,text=True)
 assert r.returncode != 0 and 'SyntaxError' in r.stderr
 print('CONFIRMED: prepare-installer.ps1 generated Python cannot parse a source/staging path containing an apostrophe.')
 print(r.stderr)
 # Start the actual sidecar at an allocated alternate port. No processing, no weights.
 with socket.socket() as s:s.bind(('127.0.0.1',0));port=s.getsockname()[1]
 e=os.environ.copy();e.update(LOCAL_TOOLS_PORT=str(port),PYTHONDONTWRITEBYTECODE='1',PYTHONUNBUFFERED='1')
 proc=subprocess.Popen([sys.executable,str(ROOT/'local_tools/server.py')],cwd=ROOT/'local_tools',env=e,stdout=subprocess.PIPE,stderr=subprocess.PIPE,text=True)
 try:
  for i in range(50):
   try:
    with urllib.request.urlopen(f'http://127.0.0.1:{port}/health',timeout=.5) as response:health=json.load(response)
    break
   except Exception:
    assert proc.poll() is None,proc.communicate()
    time.sleep(.05)
  else:raise AssertionError('sidecar not ready')
  assert health['status']=='ok'
  print(f'CONFIRMED: production sidecar listens at LOCAL_TOOLS_PORT={port}; health={health}')
  print('Windows launcher statically probes/reports $ToolsPort=8765 and does not overwrite LOCAL_TOOLS_PORT.')
 finally:
  proc.terminate()
  out,err=proc.communicate(timeout=5)
  print(out,err)
 print('All defect evidence checks completed. This means reproduction succeeded, not product fixed.')

finally:
 scratch.cleanup()
